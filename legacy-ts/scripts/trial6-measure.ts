/** Headline checks for trial 6 tuning. Usage: npx tsx scripts/trial6-measure.ts [size] [seed] */
import { draftRound, simulateCohort, type CareerRecord } from '../src/career.js';
import { summarize, median, mean, quantile } from '../tests/stats.js';

const size = Number(process.argv[2] ?? 250_000);
const seed = process.argv[3] ?? 'trial6';
const res = simulateCohort({ size, seed });
const { records, draftSlots } = res;
const s = summarize(res);
const r3 = (x: number) => Math.round(x * 1000) / 1000;
const drafted = records.filter((r) => r.draftPick !== null);
const pros = records.filter((r) => r.proTeams.length);
const out: Record<string, unknown> = {};
out.draftRateByStars = s.draftRateByStars;
out.draftedShareByStars = s.draftedShareByStars;
const fs = records.filter((r) => r.stars === 5);
const fbs = (r: CareerRecord) => r.player.history.find((h) => h.level !== 'HS');
out.fiveStarTrueFreshmanStarter = r3(fs.filter((r) => fbs(r)?.playingTime === 'starter').length / fs.length);
out.arrivalByStars = Object.fromEntries([5, 4, 3, 2, 0].map((st) => {
  const g = records.filter((r) => r.stars === st && r.signedWith === 'FBS');
  const lastCollege = (r: CareerRecord) => r.player.history.filter((h) => h.level !== 'HS' && h.level !== 'NFL').at(-1)?.overall ?? 0;
  return [st, { n: g.length, arrive: r3(mean(g.map((r) => r.player.history[3]!.overall))), gain: r3(mean(g.map((r) => lastCollege(r) - r.player.history[3]!.overall))) }];
}));
const fbsUpperStarters = records.flatMap((r) => r.player.history.filter((h) => h.level === 'FBS' && h.age >= 20 && h.playingTime === 'starter').map((h) => h.overallStart));
out.fbsUpperclassStarterMedian = median(fbsUpperStarters);
const seniorsByLevel = [...records].sort((a, b) => b.player.history[3]!.levelRating! - a.player.history[3]!.levelRating!);
const top500 = seniorsByLevel.slice(0, Math.round(500 * size / 250000));
out.top500SeniorsTwoStarOrLess = top500.filter((r) => r.stars <= 2 && r.player.position !== 'K' && r.player.position !== 'P').length;
const dips = (pred: (r: CareerRecord, i: number) => boolean) => records.flatMap((r) => r.player.history.filter((h, i) => h.adjustment !== undefined && pred(r, i)).map((h) => h.adjustment!));
const colDip = records.flatMap((r) => { const h = r.player.history[4]; return h && h.level !== 'NFL' ? [h.adjustment ?? 0] : []; });
const nflDip = records.flatMap((r) => { const h = r.player.history.find((x) => x.level === 'NFL'); return h ? [h.adjustment ?? 0] : []; });
out.dipCollegeFreshmen = { mean: r3(mean(colDip)), p10: r3(quantile(colDip, 0.1)), p90: r3(quantile(colDip, 0.9)) };
out.dipNflRookies = { mean: r3(mean(nflDip)), p10: r3(quantile(nflDip, 0.1)), p90: r3(quantile(nflDip, 0.9)) };
void dips;
const portal = records.flatMap((r) => r.portal);
out.portal = portal.reduce<Record<string, number>>((m, p) => ((m[`${p.from}:${p.reason}:${p.outcome}`] = (m[`${p.from}:${p.reason}:${p.outcome}`] ?? 0) + 1), m), {});
out.transfersByReason = records.flatMap((r) => r.transfers).reduce<Record<string, number>>((m, t) => ((m[`${t.reason}:${t.from}>${t.to}`] = (m[`${t.reason}:${t.from}>${t.to}`] ?? 0) + 1), m), {});
const early = records.filter((r) => r.notes.some((n) => n.startsWith('Declared early')));
out.earlyEntrants = { n: early.length, drafted: early.filter((r) => r.draftPick).length, udfaOrNone: early.filter((r) => !r.draftPick).length };
out.stayedProjectedTop3 = records.filter((r) => r.notes.some((n) => n.startsWith('Stayed in school'))).length;
const byPosR1 = drafted.filter((r) => draftRound(r.draftPick!, draftSlots) === 1).reduce<Record<string, number>>((m, r) => ((m[r.player.position] = (m[r.player.position] ?? 0) + 1), m), {});
out.round1ByPosition = byPosR1;
const qbs = records.filter((r) => r.player.position === 'QB' && r.draftGrade !== null).sort((a, b) => b.draftGrade! - a.draftGrade!).slice(0, 8);
out.topQBgrades = qbs.map((r) => `${Math.round(r.draftGrade!)}:${r.draftPick}`);
const all = records.filter((r) => r.draftGrade !== null).sort((a, b) => b.draftGrade! - a.draftGrade!);
out.top32ByPos = all.slice(0, 32).reduce<Record<string, number>>((m, r) => ((m[r.player.position] = (m[r.player.position] ?? 0) + 1), m), {});
out.specialistsDrafted = drafted.filter((r) => r.player.position === 'K' || r.player.position === 'P').map((r) => r.draftPick);
out.firstRoundersOutsideTop50 = s.draft.firstRoundersOutsideTop50;
const released2 = (r: CareerRecord) => r.player.history.filter((h) => h.level === 'NFL').slice(0, 2).some((h) => h.playingTime === 'unsigned' || h.playingTime === 'practiceSquad');
for (const rd of [1, 2, 3]) {
  const g = drafted.filter((r) => draftRound(r.draftPick!, draftSlots) === rd);
  out[`round${rd}OffRosterWithin2`] = `${g.filter(released2).length}/${g.length}`;
}
out.careerLength = s.nfl.careerLength;
out.topPeaks = [...pros].sort((a, b) => b.peakOverall - a.peakOverall).slice(0, 12).map((r) => `${r.player.position}${Math.round(r.peakOverall)}@${r.peakAge}`).join(' ');
out.rows90 = records.flatMap((r) => r.player.history.filter((h) => h.level === 'NFL' && h.overall >= 90)).length;
const lastAge = (r: CareerRecord) => r.player.history.at(-1)!.age;
const byPos = (pos: string) => pros.filter((r) => r.player.position === pos && r.nflSeasons >= 3);
out.retireAgeMedianByPos = Object.fromEntries(['QB', 'RB', 'WR', 'TE', 'OT', 'IOL', 'EDGE', 'DT', 'LB', 'CB', 'S', 'K', 'P'].map((p) => [p, median(byPos(p).map(lastAge))]));
out.rbStartingAt30plus = records.flatMap((r) => r.player.history.filter((h) => h.level === 'NFL' && r.player.position === 'RB' && h.age >= 30 && h.playingTime === 'starter')).length;
const nflRows = records.flatMap((r) => r.player.history.filter((h) => h.level === 'NFL' && h.playingTime === 'starter'));
out.starterSeasonsAge33plusShare = r3(nflRows.filter((h) => h.age >= 33).length / nflRows.length);
out.psSeasons = records.reduce((a, r) => a + r.practiceSquadSeasons, 0);
out.unsignedRows = records.flatMap((r) => r.player.history.filter((h) => h.playingTime === 'unsigned')).length;
out.proExit = pros.reduce<Record<string, number>>((m, r) => ((m[r.proExit ?? 'none'] = (m[r.proExit ?? 'none'] ?? 0) + 1), m), {});
out.teamsPerPro = r3(mean(pros.map((r) => r.proTeams.length)));
out.rookieOverall = s.draft.rookieOverall;
out.nflSeasonOverall = s.nfl.seasonOverall;
out.peakAge = s.nfl.medianPeakAge;
out.recruiting = s.recruiting;
out.trouble = s.trouble;
out.levelRatings = s.levelRatings;
out.smallSchools = { ...s.smallSchools, transferRoutes: undefined };
out.hs = s.hs;
out.potential = s.potential;
console.log(JSON.stringify(out, null, 1));
