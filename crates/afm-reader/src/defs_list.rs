macro_rules! fbs_seasons {
    () => {
        "programs__seasons s JOIN programs p ON p._row = s._parent"
    };
}

macro_rules! titles {
    () => {
        "WITH t AS (SELECT s._parent AS prog, s.year AS y FROM programs__seasons s JOIN programs p ON p._row = s._parent
            WHERE p.division = 'FBS' AND s.national_title = 1),
         e AS (SELECT DISTINCT y AS e FROM t WHERE y >= (SELECT MIN(y) + 14 FROM t)),
         c AS (SELECT e.e, t.prog, COUNT(*) AS n FROM e JOIN t ON t.y BETWEEN e.e - 14 AND e.e GROUP BY e.e, t.prog) "
    };
}

macro_rules! drafted {
    () => {
        "WITH d AS (
            SELECT a.position AS pos, a.stars, a.class_of, a.pick AS pick, json_extract(a.pro__draft, '$[0]') AS year,
                   json_extract(a.pro__draft, '$[1]') AS round, CAST(json_extract(a.colleges, '$[#-1]') AS INTEGER) AS college,
                   a.player__body__weight AS weight, a.player__body__height AS height
              FROM alumni a WHERE a.pick IS NOT NULL
            UNION ALL
            SELECT p.player__position, p.stars, p.class_of, NULL, json_extract(p.pro__draft, '$[0]'),
                   json_extract(p.pro__draft, '$[1]'), p.college, p.player__body__weight, p.player__body__height
              FROM people p WHERE p.pro__draft IS NOT NULL AND json_extract(p.pro__draft, '$[1]') IS NOT NULL
               AND p.player__id NOT IN (SELECT player__id FROM alumni WHERE player__id IS NOT NULL)) "
    };
}

macro_rules! recruits {
    () => {
        "WITH r AS (SELECT stars, class_of, pick IS NOT NULL AS d FROM alumni
                    UNION ALL SELECT stars, class_of, pro__draft IS NOT NULL FROM people
                    WHERE player__id NOT IN (SELECT player__id FROM alumni WHERE player__id IS NOT NULL)),
         span AS (SELECT MIN(year) + 4 AS lo, MAX(year) - 5 AS hi FROM programs__seasons) "
    };
}

/// Per team game in the game log: box rows (`_i` 0 home, 1 away) of
/// regular-season games at one level (`stream`).
macro_rules! box_of {
    ($stream:literal) => {
        concat!(
            "log_games__box b JOIN log_games g ON g._row = b._parent WHERE g.stream = '",
            $stream,
            "' AND COALESCE(g.kind, 'regular') = 'regular' AND COALESCE(g.standin, 0) = 0"
        )
    };
}

macro_rules! fbs_box {
    () => {
        "log_games__box b JOIN log_games g ON g._row = b._parent
         JOIN programs p ON p._row = json_extract(g.teams, '$[' || b._i || ']')
         WHERE g.stream = 'college' AND p.division = 'FBS' AND COALESCE(g.standin, 0) = 0"
    };
}

