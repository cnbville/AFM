//! People and their calendars as world files hold them (memory diet, lane
//! M1): every field flat, by name, in the order files always had, while in
//! memory a person's college-and-later part (`Later`) and the rest of his
//! calendar (`CalMore`) are kept only once he uses them (`stored::Stored`).
//! Reading goes through `file::*`, writing (and `Debug`) through `view::*`;
//! both list every field, and the conversions name every field, so a field
//! added to `Person` or `PersonCal` without them doesn't build. Files, the
//! world log's store prints and the World Reader's tables see exactly what
//! they saw before.

use super::*;
use crate::world::stored::Stored;

/// Written only when there is one (the field's own rule before the split).
fn none<T>(v: &&Option<T>) -> bool {
    v.is_none()
}
/// Written only when it holds something.
fn empty<T>(v: &&Vec<T>) -> bool {
    v.is_empty()
}

