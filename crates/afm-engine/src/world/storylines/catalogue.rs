#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalogue_matches_its_index() {
        assert_eq!(K::ALL.len(), CATALOGUE.len());
        let keys: Vec<&str> = CATALOGUE.iter().map(|d| d.key).collect();
        for (k, d) in CATALOGUE.iter().enumerate() {
            assert!(!d.endings.is_empty(), "{} has no endings", d.key);
            assert!(!d.question.is_empty());
            assert_eq!(keys.iter().filter(|x| **x == d.key).count(), 1, "{} twice", d.key);
            assert!(d.levels != 0, "{}", d.key);
            assert!(d.quiet >= 7, "{}", d.key);
            assert_eq!(by_key(d.key), Some(k as u16));
        }
        // The enum and the table agree by key spelling.
        assert_eq!(K::QbBattle.def().key, "qb_battle");
        assert_eq!(K::HotSeat.def().key, "hot_seat");
        assert_eq!(K::NewCoach.def().key, "new_coach");
        assert_eq!(K::YourMilestone.def().key, "your_milestone");
        assert_eq!(K::RoomRift.def().key, "room_rift");
        assert_eq!(K::TopRecruit.def().key, "top_recruit");
        // Every family has kinds.
        for f in Family::ALL {
            assert!(CATALOGUE.iter().filter(|d| d.family == f).count() >= 4, "{f:?}");
        }
    }
}
