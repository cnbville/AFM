/// A coaching rating a story tests: handling it well teaches it (S10).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum Rating {
    Motivation,
    Discipline,
    Relationships,
    Recruiting,
    Network,
    GameManagement,
    Scheme,
    PlayCalling,
    Adaptation,
    Evaluation,
    Negotiating,
}

impl Rating {
    pub const ALL: [Rating; 11] = [
        Rating::Motivation,
        Rating::Discipline,
        Rating::Relationships,
        Rating::Recruiting,
        Rating::Network,
        Rating::GameManagement,
        Rating::Scheme,
        Rating::PlayCalling,
        Rating::Adaptation,
        Rating::Evaluation,
        Rating::Negotiating,
    ];
    pub fn name(self) -> &'static str {
        match self {
            Rating::Motivation => "Motivation",
            Rating::Discipline => "Discipline",
            Rating::Relationships => "Relationships",
            Rating::Recruiting => "Recruiting",
            Rating::Network => "Network",
            Rating::GameManagement => "Game management",
            Rating::Scheme => "Scheme",
            Rating::PlayCalling => "Play calling",
            Rating::Adaptation => "In-game adaptation",
            Rating::Evaluation => "Evaluation",
            Rating::Negotiating => "Negotiating",
        }
    }
    pub fn index(self) -> usize {
        Rating::ALL.iter().position(|&r| r == self).unwrap_or(0)
    }
    pub fn from_index(k: usize) -> Rating {
        Rating::ALL.get(k).copied().unwrap_or(Rating::Motivation)
    }
    /// The rating as it stands for a coach.
    pub fn get(self, a: &Ability, y: Option<&Yours>) -> f64 {
        match self {
            Rating::Motivation => a.motivation,
            Rating::Discipline => a.discipline,
            Rating::Relationships => a.relationships,
            Rating::Recruiting => a.recruiting,
            Rating::Network => a.network,
            Rating::GameManagement => a.game_management,
            Rating::Scheme => a.scheme,
            Rating::PlayCalling => y.map_or(10.0, |y| y.play_calling),
            Rating::Adaptation => y.map_or(10.0, |y| y.adaptation),
            Rating::Evaluation => y.map_or(10.0, |y| y.evaluation),
            Rating::Negotiating => y.map_or(10.0, |y| y.negotiating),
        }
    }
    /// Adds to the rating, up to 20.
    pub fn add(self, a: &mut Ability, y: Option<&mut Yours>, by: f64) {
        let v = match self {
            Rating::Motivation => &mut a.motivation,
            Rating::Discipline => &mut a.discipline,
            Rating::Relationships => &mut a.relationships,
            Rating::Recruiting => &mut a.recruiting,
            Rating::Network => &mut a.network,
            Rating::GameManagement => &mut a.game_management,
            Rating::Scheme => &mut a.scheme,
            _ => {
                let Some(y) = y else { return };
                match self {
                    Rating::PlayCalling => &mut y.play_calling,
                    Rating::Adaptation => &mut y.adaptation,
                    Rating::Evaluation => &mut y.evaluation,
                    _ => &mut y.negotiating,
                }
            }
        };
        *v = (*v + by).clamp(1.0, 20.0);
    }
}

/// Level bits: where a kind happens in real life.
pub const HS: u8 = 1;
pub const COL: u8 = 2;
pub const NFL: u8 = 4;
/// Recruiting crosses high school and college.
pub const REC: u8 = 8;
/// The other pro leagues (the CFL, arena, the spring leagues).
pub const OTH: u8 = 16;
pub const ALL: u8 = HS | COL | NFL | OTH;

pub fn level_bit(l: Level) -> u8 {
    match l {
        Level::HighSchool => HS,
        Level::College => COL,
        Level::Nfl => NFL,
        Level::Recruiting => REC,
        Level::Other => OTH,
        Level::World => 0,
    }
}

/// One kind of story.
#[derive(Debug)]
pub struct Def {
    pub key: &'static str,
    pub family: Family,
    pub name: &'static str,
    pub levels: u8,
    /// 0-100: how much rides on it before its cast's fame and market.
    pub stakes: u8,
    /// -1 bad news for its team, 0 mixed, 1 good news.
    pub tone: i8,
    /// Everyone sees it from day one (a firing, an arrest, a streak); the
    /// rest start private and go public only through a person (S2).
    pub public: bool,
    /// Days without a beat before it fizzles.
    pub quiet: u16,
    /// The question the public asks: {lead} {rival} {team} {other} {n}.
    pub question: &'static str,
    /// Its endings and how each reads for its team and decider.
    pub endings: &'static [(&'static str, f32)],
    pub tests: &'static [Rating],
    /// What it adds to a job's volatility while a new coach inherits it (S10).
    pub volatile: f32,
    pub real: &'static str,
}

impl Def {
    pub fn at(&self, l: Level) -> bool {
        self.levels & level_bit(l) != 0
    }
    /// The ending's index (1-based; 0 none) by key.
    pub fn ending(&self, key: &str) -> u8 {
        self.endings.iter().position(|e| e.0 == key).map_or(0, |k| k as u8 + 1)
    }
    pub fn ending_key(&self, code: u8) -> &'static str {
        if code == 0 { "" } else { self.endings.get(code as usize - 1).map_or("", |e| e.0) }
    }
    pub fn valence(&self, code: u8) -> f32 {
        if code == 0 { 0.0 } else { self.endings.get(code as usize - 1).map_or(0.0, |e| e.1) }
    }
}

