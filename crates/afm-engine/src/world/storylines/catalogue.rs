impl K {
    pub fn def(self) -> &'static Def {
        &CATALOGUE[self as usize]
    }
    pub fn id(self) -> u16 {
        self as u16
    }
}

/// The definition of a kind by its index.
pub fn def(kind: u16) -> &'static Def {
    CATALOGUE.get(kind as usize).unwrap_or(&CATALOGUE[0])
}

pub fn by_key(key: &str) -> Option<u16> {
    CATALOGUE.iter().position(|d| d.key == key).map(|k| k as u16)
}

