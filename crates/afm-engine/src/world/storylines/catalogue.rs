//! The catalogue (S1, S6): every kind of story real football tells every
//! year, as data. Each kind lists the levels it happens at, how much rides
//! on it, whether it is good or bad news for the team it is about, whether
//! everyone sees it from the first day, how long it can go quiet before it
//! fizzles, the question the public asks, its endings (each with how it
//! reads for the team and its decider, -1 to 1), the coaching ratings it
//! tests (your lesson points go there, S10), how much it adds to a job's
//! volatility when a new coach inherits it, and the real case it is
//! modelled on. Text lives in the line banks (`data/lines/stories/
//! storylines.txt`), keyed by the kind's key. The detectors (`detect.rs`)
//! are the only code a kind needs.
//!
//! Stakes, quiet days and volatility weights are Claude's picks (proposed,
//! not confirmed).

