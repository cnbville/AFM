//! The Attributes page's default lists: for each position the skills that
//! come into play (`core`, the position's eight skill families) and the
//! "Also in play" skills with a short reason each. Measured from the match
//! engine's reads of every skill over 800 NFL games and the position's
//! weights, then reviewed twice (engine, scout); how and why:
//! `docs/reference/how-it-works/ratings.md`, "The Attributes page's lists".
//! Agreed by Cain 2026-11-13. K, P and LS show their families only.

use afm_engine::attributes::Attr::{self, *};
use afm_engine::positions::Position;

/// One position's list.
pub(crate) struct PosList {
    /// The skills of the position's eight families, each once.
    pub core: &'static [Attr],
    /// Skills outside the families that still come into play, each with
    /// why, in the order the page shows them.
    pub also: &'static [(Attr, &'static str)],
}

pub(crate) fn list(pos: Position) -> &'static PosList {
    match pos {
        Position::QB => &QB,
        Position::RB => &RB,
        Position::WR => &WR,
        Position::TE => &TE,
        Position::OT => &OT,
        Position::IOL => &IOL,
        Position::EDGE => &EDGE,
        Position::DT => &DT,
        Position::LB => &LB,
        Position::CB => &CB,
        Position::S => &S,
        Position::K => &K,
        Position::P => &P,
        Position::LS => &LS,
    }
}

